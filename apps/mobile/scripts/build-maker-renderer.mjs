import { build } from "esbuild";
import { copyFile, mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["scripts/maker-renderer.js"],
  bundle: true,
  format: "iife",
  minify: true,
  write: false,
  target: "chrome100",
  legalComments: "inline",
});
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data: blob:; connect-src 'none'"><style>html,body{margin:0;width:100%;height:100%;overflow:hidden}canvas{display:block;width:100%;height:100%;touch-action:none}</style></head><body><script>${result.outputFiles[0].text.replaceAll("</script", "<\\/script")}</script></body></html>`;
await writeFile(
  root + "lib/maker-renderer.generated.ts",
  "// Generated by scripts/build-maker-renderer.mjs; do not edit.\nexport default " +
    JSON.stringify(html) +
    ";\n",
);
console.log(`Bundled local renderer: ${Math.round(html.length / 1024)} KiB`);

// Copy the existing versioned GLB asset data, never web UI or browser hooks.
await copyFile(
  root + "../../packages/views/build/catalog/catalog.generated.ts",
  root + "lib/maker-catalog.generated.ts",
);

const thumbnailRoot = root + "../../packages/views/build/catalog/";
const registry = await readFile(
  thumbnailRoot + "catalog-thumbnails.generated.ts",
  "utf8",
);
const files = Object.fromEntries(
  [
    ...registry.matchAll(
      /import (thumbnail\d+) from "\.\/thumbnails\/(.*?)";/g,
    ),
  ].map((m) => [m[1], m[2]]),
);
const version = registry.match(/LDRAW_THUMBNAIL_CATALOG_VERSION = "(.*?)"/)[1];
await mkdir(root + "assets/maker", { recursive: true });
const entries = [];
for (const m of registry.matchAll(
  /"([^"\n]+)": \{ src: assetURL\((thumbnail\d+)\)/g,
)) {
  const file = files[m[2]];
  await copyFile(
    thumbnailRoot + "thumbnails/" + file,
    root + "assets/maker/" + file,
  );
  entries.push(
    JSON.stringify(m[1]) +
      ": require(" +
      JSON.stringify("../assets/maker/" + file) +
      ")",
  );
}
await writeFile(
  root + "lib/maker-thumbnails.generated.ts",
  "// Generated from the versioned LDraw thumbnail assets.\nexport const thumbnailVersion = " +
    JSON.stringify(version) +
    ";\nexport const makerThumbnails: Record<string, number> = {\n" +
    entries.join(",\n") +
    "\n};\n",
);

// Remove only obsolete files owned by this generator after the new registry is saved.
const currentThumbnails = new Set(Object.values(files));
for (const file of await readdir(root + "assets/maker")) {
  if (/-ldraw-studio-v\d+\.webp$/.test(file) && !currentThumbnails.has(file)) {
    await unlink(root + "assets/maker/" + file);
  }
}
