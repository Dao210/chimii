import { createServer } from "node:net";
import { spawn } from "node:child_process";
import { mkdir, mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const rendererRoot = join(repositoryRoot, "tools/ldraw-thumbnails");
const catalogRoot = join(repositoryRoot, "packages/views/build/catalog");
const outputRoot = join(catalogRoot, "thumbnails");
const manifestPath = join(catalogRoot, "catalog-thumbnails.generated.ts");

function freePort() {
  return new Promise((resolvePort, reject) => {
    const server = createServer();
    server.once("error", reject);
    server.listen(0, "127.0.0.1", () => {
      const address = server.address();
      if (!address || typeof address === "string") {
        server.close();
        reject(new Error("Could not reserve a thumbnail renderer port"));
        return;
      }
      server.close((error) => error ? reject(error) : resolvePort(address.port));
    });
  });
}

async function waitForRenderer(url, serverProcess, output) {
  for (let attempt = 0; attempt < 120; attempt += 1) {
    if (serverProcess.exitCode != null) {
      throw new Error(`Thumbnail renderer exited early.\n${output.join("")}`);
    }
    try {
      const response = await fetch(url);
      if (response.ok) return;
    } catch {
      // Vite is still starting.
    }
    await new Promise((resolveWait) => setTimeout(resolveWait, 100));
  }
  throw new Error(`Thumbnail renderer did not start.\n${output.join("")}`);
}

function safeName(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function renderManifest(metadata, assets) {
  const lines = [
    "// Code generated by scripts/generate-ldraw-thumbnails.mjs. DO NOT EDIT.",
    "",
  ];
  assets.forEach((asset, index) => {
    lines.push(`import thumbnail${index} from ${JSON.stringify(`./thumbnails/${asset.filename}`)};`);
  });
  lines.push(
    "",
    "export interface LDrawThumbnailAsset {",
    "  src: string;",
    "  ldrawID: string;",
    "  colorCode: number;",
    "  assetHash: string;",
    "  width: number;",
    "  height: number;",
    "}",
    "",
    "function assetURL(asset: string | { readonly src: string }): string {",
    "  return typeof asset === \"string\" ? asset : asset.src;",
    "}",
    "",
    `export const LDRAW_THUMBNAIL_CATALOG_VERSION = ${JSON.stringify(metadata.catalogVersion)};`,
    `export const LDRAW_THUMBNAIL_RENDER_PRESET_VERSION = ${JSON.stringify(metadata.renderPresetVersion)};`,
    `export const LDRAW_THUMBNAIL_WIDTH = ${metadata.width};`,
    `export const LDRAW_THUMBNAIL_HEIGHT = ${metadata.height};`,
    `export const LDRAW_THUMBNAIL_COLORS = ${JSON.stringify(metadata.colors)} as const;`,
    "",
    "export const LDRAW_THUMBNAILS: Readonly<Record<string, LDrawThumbnailAsset>> = {",
  );
  assets.forEach((asset, index) => {
    const key = `${asset.ldrawID.toLowerCase()}:${asset.colorCode}`;
    lines.push(
      `  ${JSON.stringify(key)}: { src: assetURL(thumbnail${index}), ldrawID: ${JSON.stringify(asset.ldrawID)}, colorCode: ${asset.colorCode}, assetHash: ${JSON.stringify(asset.assetHash)}, width: LDRAW_THUMBNAIL_WIDTH, height: LDRAW_THUMBNAIL_HEIGHT },`,
    );
  });
  lines.push(
    "};",
    "",
    "export function getLDrawThumbnail(ldrawID: string, colorCode: number): LDrawThumbnailAsset | undefined {",
    "  return LDRAW_THUMBNAILS[`${ldrawID.toLowerCase()}:${colorCode}`];",
    "}",
    "",
  );
  return lines.join("\n");
}

async function main() {
  const port = await freePort();
  const url = `http://127.0.0.1:${port}`;
  const output = [];
  const pnpmCommand = process.platform === "win32" ? "pnpm.cmd" : "pnpm";
  const vite = spawn(
    pnpmCommand,
    ["exec", "vite", "--host", "127.0.0.1", "--port", String(port), "--strictPort"],
    { cwd: rendererRoot, stdio: ["ignore", "pipe", "pipe"] },
  );
  vite.stdout.on("data", (chunk) => output.push(chunk.toString()));
  vite.stderr.on("data", (chunk) => output.push(chunk.toString()));

  const temporaryRoot = await mkdtemp(join(tmpdir(), "chimii-ldraw-thumbnails-"));
  let browser;
  try {
    await waitForRenderer(url, vite, output);
    browser = await chromium.launch({
      headless: true,
      args: [
        "--enable-unsafe-swiftshader",
        "--use-gl=angle",
        "--use-angle=swiftshader",
        "--disable-gpu-sandbox",
      ],
    });
    const page = await browser.newPage({
      viewport: { width: 640, height: 400 },
      deviceScaleFactor: 1,
    });
    const pageErrors = [];
    page.on("pageerror", (error) => pageErrors.push(error.message));
    page.on("console", (message) => {
      if (message.type() === "error") pageErrors.push(message.text());
    });
    page.on("requestfailed", (request) => {
      pageErrors.push(`${request.url()}: ${request.failure()?.errorText ?? "request failed"}`);
    });
    await page.goto(url, { waitUntil: "networkidle" });
    try {
      await page.waitForFunction(() => Boolean(window.ldrawThumbnailRenderer), undefined, { timeout: 10_000 });
    } catch (error) {
      throw new Error(`Thumbnail renderer did not initialise: ${error.message}\n${pageErrors.join("\n")}\n${output.join("")}`);
    }
    const metadata = await page.evaluate(() => window.ldrawThumbnailRenderer.metadata);
    const assets = [];

    for (const part of metadata.parts) {
      for (const colorCode of metadata.colors) {
        const dataURL = await page.evaluate(
          ({ ldrawID, color }) => window.ldrawThumbnailRenderer.renderThumbnail(ldrawID, color),
          { ldrawID: part.ldrawID, color: colorCode },
        );
        const prefix = "data:image/webp;base64,";
        if (!dataURL.startsWith(prefix)) throw new Error(`Browser did not export WebP for ${part.ldrawID}:${colorCode}`);
        const buffer = Buffer.from(dataURL.slice(prefix.length), "base64");
        if (buffer.length < 1024) throw new Error(`Thumbnail is unexpectedly small for ${part.ldrawID}:${colorCode}`);
        const filename = `${safeName(part.ldrawID)}-c${colorCode}-${part.assetHash.slice(0, 16)}-${safeName(metadata.renderPresetVersion)}.webp`;
        await writeFile(join(temporaryRoot, filename), buffer);
        assets.push({ ...part, colorCode, filename });
      }
    }

    if (pageErrors.length > 0) throw new Error(`Thumbnail renderer errors:\n${pageErrors.join("\n")}`);
    const expectedCount = metadata.parts.length * metadata.colors.length;
    if (assets.length !== expectedCount) throw new Error(`Generated ${assets.length} thumbnails; expected ${expectedCount}`);

    await mkdir(dirname(outputRoot), { recursive: true });
    await rm(outputRoot, { recursive: true, force: true });
    await rename(temporaryRoot, outputRoot);
    await writeFile(manifestPath, renderManifest(metadata, assets));

    const totalBytes = await assets.reduce(async (pending, asset) => {
      const total = await pending;
      return total + (await readFile(join(outputRoot, asset.filename))).byteLength;
    }, Promise.resolve(0));
    console.log(`Generated ${assets.length} LDraw thumbnails (${(totalBytes / 1024).toFixed(1)} KiB) in ${relative(repositoryRoot, outputRoot)}`);
  } finally {
    if (browser) await browser.close();
    if (vite.exitCode == null) vite.kill("SIGTERM");
    await rm(temporaryRoot, { recursive: true, force: true });
  }
}

await main();
